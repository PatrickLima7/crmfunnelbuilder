import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { transpileModule } from 'typescript';
const asModule = source => `data:text/javascript;base64,${Buffer.from(transpileModule(source, { compilerOptions: { target: 9, module: 99 } }).outputText).toString('base64')}`;
const calendar = asModule(await readFile(new URL('../src/lib/lead-categories.ts', import.meta.url), 'utf8'));
const scheduling = (await readFile(new URL('../src/lib/callback-scheduling.ts', import.meta.url), 'utf8')).replace('"./lead-categories"', JSON.stringify(calendar));
const { suggestCallback, requiresCallback, validCallback } = await import(asModule(scheduling));
assert.equal(suggestCallback(new Date('2026-10-01T16:00:00Z')), '2026-10-02T18:00:00.000Z');
assert.equal(suggestCallback(new Date('2026-10-02T02:30:00Z')), '2026-10-03T04:30:00.000Z');
assert.equal(suggestCallback(new Date('2026-12-31T16:45:00Z')), '2027-01-01T18:45:00.000Z');
for (const result of ['interessado', 'pensar', 'retorno', 'desligou']) assert.equal(requiresCallback(result), true);
for (const result of ['convertido', 'sem_interesse', null]) assert.equal(requiresCallback(result), false);
for (const value of ['', null, undefined, 'invalid']) assert.equal(validCallback(value), false);
const { parseInsights, insightIndex, INSIGHT_INTERVAL_MS: interval } = await import(asModule(await readFile(new URL('../src/lib/insight-messages.ts', import.meta.url), 'utf8')));
const messages = parseInsights([{category:'tecnica',text:'Uma dica'}, {category:'operacao',text:'Uma dica'}, {category:'invalid',text:'x'}, {category:'motivacional',text:'Outra dica'}]);
assert.equal(messages.length, 2);
assert.equal(insightIndex(interval - 1, 2), 0);
assert.equal(insightIndex(interval, 2), 1);
assert.equal(insightIndex(interval * 2, 2), 0);
assert.equal(insightIndex(interval * 5, 3), 2, 'background tab catches up');
assert.ok(parseInsights(null).length >= 3);
assert.ok(parseInsights([]).length >= 3);
console.log('PASS: Brasília suggestion, day/year rollover, required outcomes, blank dates, 15-minute rotation and config validation.');
